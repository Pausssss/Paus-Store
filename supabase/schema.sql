-- -----------------------------
-- PUBLIC RPC: VALIDATE ONE COUPON
-- -----------------------------
create or replace function public.validate_coupon(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  c public.coupons%rowtype;
  normalized text := upper(trim(coalesce(p_code, '')));
begin
  if normalized = '' then
    return null;
  end if;

  select * into c
  from public.coupons
  where upper(code) = normalized
    and active = true
  limit 1;

  if not found then
    return null;
  end if;

  return jsonb_build_object(
    'code', c.code,
    'type', c.type,
    'value', c.value,
    'label', coalesce(c.label, c.code)
  );
end;
$$;

revoke all on function public.validate_coupon(text) from public;
grant execute on function public.validate_coupon(text) to anon, authenticated;

-- -----------------------------
-- PUBLIC RPC: NEWSLETTER
-- -----------------------------
create or replace function public.subscribe_newsletter(p_email text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized text := lower(trim(coalesce(p_email, '')));
begin
  if length(normalized) > 254
     or normalized !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then
    raise exception 'Email không hợp lệ';
  end if;

  insert into public.newsletter_subscribers(email, active)
  values (normalized, true)
  on conflict (email) do update set active = true;

  return true;
end;
$$;

revoke all on function public.subscribe_newsletter(text) from public;
grant execute on function public.subscribe_newsletter(text) to anon, authenticated;

-- -----------------------------
-- PUBLIC RPC: CREATE ORDER SAFELY
-- -----------------------------
-- Browser chỉ gửi product id + size + qty. Giá, giảm giá, ship và total
-- được tính lại hoàn toàn trong PostgreSQL từ dữ liệu hiện tại.
create or replace function public.create_public_order(
  p_customer jsonb,
  p_items jsonb,
  p_coupon text default null,
  p_shipping_method text default 'standard'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  raw_item jsonb;
  p public.products%rowtype;
  qty integer;
  size_key text;
  variant_key text;
  selected_variant jsonb;
  unit_price bigint;
  line_total bigint;
  clean_items jsonb := '[]'::jsonb;
  subtotal_value bigint := 0;
  discount_value bigint := 0;
  shipping_value bigint := 0;
  total_value bigint := 0;
  coupon_row public.coupons%rowtype;
  coupon_code text := upper(trim(coalesce(p_coupon, '')));
  settings jsonb := '{}'::jsonb;
  free_ship_threshold bigint := 1000000;
  standard_shipping bigint := 35000;
  express_shipping bigint := 55000;
  shipping_method text := lower(trim(coalesce(p_shipping_method, 'standard')));
  customer_clean jsonb;
  order_code_value text;
  order_row public.orders%rowtype;
  attempt integer := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 then
    raise exception 'Giỏ hàng trống';
  end if;

  if jsonb_array_length(p_items) > 30 then
    raise exception 'Giỏ hàng có quá nhiều dòng sản phẩm';
  end if;

  customer_clean := jsonb_build_object(
    'name', left(trim(coalesce(p_customer->>'name', '')), 120),
    'phone', left(trim(coalesce(p_customer->>'phone', '')), 30),
    'email', left(trim(coalesce(p_customer->>'email', '')), 254),
    'address', left(trim(coalesce(p_customer->>'address', '')), 300),
    'city', left(trim(coalesce(p_customer->>'city', '')), 120),
    'payment', left(trim(coalesce(p_customer->>'payment', 'cod')), 30),
    'note', left(trim(coalesce(p_customer->>'note', '')), 1000)
  );

  if length(customer_clean->>'name') < 2 then
    raise exception 'Vui lòng nhập họ tên';
  end if;
  if length(customer_clean->>'phone') < 8 then
    raise exception 'Số điện thoại chưa hợp lệ';
  end if;
  if length(customer_clean->>'address') < 3 then
    raise exception 'Vui lòng nhập địa chỉ';
  end if;
  if length(customer_clean->>'city') < 2 then
    raise exception 'Vui lòng nhập tỉnh/thành';
  end if;

  for raw_item in select value from jsonb_array_elements(p_items)
  loop
    qty := greatest(1, least(20, coalesce((raw_item->>'qty')::integer, 1)));
    size_key := left(trim(coalesce(raw_item->>'size', '')), 40);
    variant_key := left(trim(coalesce(raw_item->>'variant', 'default')), 80);

    select * into p
    from public.products
    where id = (raw_item->>'id')::bigint
      and active = true
    limit 1;

    if not found then
      raise exception 'Có sản phẩm không còn bán';
    end if;

    if jsonb_array_length(coalesce(p.variants,'[]'::jsonb)) > 0 then
      select value into selected_variant from jsonb_array_elements(p.variants) where value->>'id' = variant_key limit 1;
      if selected_variant is null then raise exception 'Màu / phiên bản không còn khả dụng cho %', p.name; end if;
      if not ((selected_variant->'sizes') ? size_key) then raise exception 'Size % không còn khả dụng cho %', size_key, p.name; end if;
      begin unit_price := ((selected_variant->'sizes')->>size_key)::bigint; exception when others then raise exception 'Giá sản phẩm không hợp lệ'; end;
    else
      if not (p.sizes ? size_key) then raise exception 'Size % không còn khả dụng cho %', size_key, p.name; end if;
      begin unit_price := (p.sizes->>size_key)::bigint; exception when others then raise exception 'Giá sản phẩm không hợp lệ'; end;
      selected_variant := jsonb_build_object('id','default','label','Mặc định','image',p.image);
    end if;

    if unit_price <= 0 then
      raise exception 'Giá sản phẩm không hợp lệ';
    end if;

    line_total := unit_price * qty;
    subtotal_value := subtotal_value + line_total;

    clean_items := clean_items || jsonb_build_array(
      jsonb_build_object(
        'id', p.id,
        'slug', p.slug,
        'name', p.name,
        'brand', p.brand,
        'image', coalesce(selected_variant->>'image', p.image),
        'variant', variant_key,
        'variantLabel', coalesce(selected_variant->>'label','Mặc định'),
        'size', size_key,
        'qty', qty,
        'unit', unit_price,
        'line', line_total
      )
    );
  end loop;

  select data into settings
  from public.store_settings
  where id = 1;

  settings := coalesce(settings, '{}'::jsonb);
  free_ship_threshold := coalesce((settings->>'freeShipThreshold')::bigint, free_ship_threshold);
  standard_shipping := coalesce((settings->>'standardShipping')::bigint, standard_shipping);
  express_shipping := coalesce((settings->>'expressShipping')::bigint, express_shipping);

  if coupon_code <> '' then
    select * into coupon_row
    from public.coupons
    where upper(code) = coupon_code
      and active = true
    limit 1;

    if found then
      if coupon_row.type = 'percent' then
        discount_value := round(subtotal_value * least(coupon_row.value, 100)::numeric / 100)::bigint;
      elsif coupon_row.type = 'fixed' then
        discount_value := least(subtotal_value, coupon_row.value);
      elsif coupon_row.type = 'shipping' then
        shipping_value := 0;
      end if;
    else
      coupon_code := '';
    end if;
  end if;

  if coupon_row.type is distinct from 'shipping' then
    if shipping_method = 'express' then
      shipping_value := express_shipping;
    elsif free_ship_threshold > 0 and subtotal_value >= free_ship_threshold then
      shipping_value := 0;
    else
      shipping_value := standard_shipping;
    end if;
  end if;

  total_value := greatest(0, subtotal_value - discount_value + shipping_value);

  -- Mã đơn ngắn, dễ đọc. Loop tránh collision hiếm gặp.
  loop
    attempt := attempt + 1;
    order_code_value := 'PAUS' || to_char(now(), 'YYMMDD') || upper(substr(encode(gen_random_bytes(4), 'hex'), 1, 6));
    exit when not exists(select 1 from public.orders where order_code = order_code_value);
    if attempt >= 5 then
      raise exception 'Không thể tạo mã đơn';
    end if;
  end loop;

  insert into public.orders(
    order_code,
    customer,
    items,
    subtotal,
    discount,
    shipping,
    total,
    coupon,
    status,
    payment,
    note
  ) values (
    order_code_value,
    customer_clean,
    clean_items,
    subtotal_value,
    discount_value,
    shipping_value,
    total_value,
    nullif(coupon_code, ''),
    'Chờ xác nhận',
    customer_clean->>'payment',
    nullif(customer_clean->>'note', '')
  ) returning * into order_row;

  return jsonb_build_object(
    'id', order_row.order_code,
    'order_code', order_row.order_code,
    'customer', order_row.customer,
    'items', order_row.items,
    'subtotal', order_row.subtotal,
    'discount', order_row.discount,
    'shipping', order_row.shipping,
    'total', order_row.total,
    'coupon', order_row.coupon,
    'status', order_row.status,
    'payment', order_row.payment,
    'createdAt', order_row.created_at,
    'created_at', order_row.created_at
  );
end;
$$;

revoke all on function public.create_public_order(jsonb, jsonb, text, text) from public;
grant execute on function public.create_public_order(jsonb, jsonb, text, text) to anon, authenticated;

