for each row execute function public.set_updated_at();

-- -----------------------------
-- ADMIN CHECK
-- -----------------------------
create or replace function public.is_paus_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1
    from public.admins
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_paus_admin() from public;
grant execute on function public.is_paus_admin() to anon, authenticated;

