-- Nâng cấp schema sản phẩm từ phiên bản cũ nếu database đã tồn tại.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='notes')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='features') then
    alter table public.products rename column notes to features;
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='longevity')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='material') then
    alter table public.products rename column longevity to material;
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='season')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='fit') then
    alter table public.products rename column season to fit;
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='occasion')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='origin') then
    alter table public.products rename column occasion to origin;
  end if;
  if exists (select 1 from information_schema.tables where table_schema='public' and table_name='products')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='variants') then
    alter table public.products add column variants jsonb not null default '[]'::jsonb;
  end if;
end $$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  brand text not null,
  name text not null,
  category text not null default 'Sneakers',
  collection text not null default 'MLB Footwear',
  badge text,
  featured boolean not null default false,
  rating numeric(2,1) not null default 5.0 check (rating >= 0 and rating <= 5),
  reviews integer not null default 0 check (reviews >= 0),
  features jsonb not null default '[]'::jsonb,
  short text not null default '',
  description text not null default '',
  material text not null default '',
  fit text not null default '',
  origin text not null default '',
  style text not null default '',
  image text not null default '',
  gallery jsonb not null default '[]'::jsonb,
  sizes jsonb not null default '{}'::jsonb,
  variants jsonb not null default '[]'::jsonb,
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_features_array check (jsonb_typeof(features) = 'array'),
  constraint products_gallery_array check (jsonb_typeof(gallery) = 'array'),
  constraint products_sizes_object check (jsonb_typeof(sizes) = 'object'),
  constraint products_variants_array check (jsonb_typeof(variants) = 'array')
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  customer jsonb not null default '{}'::jsonb,
  items jsonb not null default '[]'::jsonb,
  subtotal bigint not null default 0 check (subtotal >= 0),
  discount bigint not null default 0 check (discount >= 0),
  shipping bigint not null default 0 check (shipping >= 0),
  total bigint not null default 0 check (total >= 0),
  coupon text,
  status text not null default 'Chờ xác nhận',
  payment text,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_items_array check (jsonb_typeof(items) = 'array')
);

create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  type text not null check (type in ('percent', 'fixed', 'shipping')),
  value bigint not null default 0 check (value >= 0),
  label text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id integer primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

